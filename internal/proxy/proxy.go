// Package proxy assembles the request pipeline in front of the upstream service.
package proxy

import (
	"fmt"
	"log/slog"
	"net"
	"net/http"
	"net/http/httputil"
	"net/url"
	"time"

	"github.com/gykim-l2softlab/smart_buckler/internal/redact"
	"github.com/gykim-l2softlab/smart_buckler/internal/store"
	"github.com/gykim-l2softlab/smart_buckler/internal/waf"
)

// Inspector evaluates a request before it is forwarded.
// closeTx must be called once the request has been fully forwarded.
type Inspector interface {
	Inspect(r *http.Request) (v waf.Verdict, closeTx func(), err error)
}

// Recorder stores security events without blocking.
type Recorder interface {
	Record(store.Event)
}

// maxPathLen bounds the stored path so hostile URLs cannot bloat the event store.
const maxPathLen = 2048

// Handler is the reverse proxy with the inspection pipeline.
type Handler struct {
	inspector Inspector
	recorder  Recorder
	log       *slog.Logger
	upstream  *httputil.ReverseProxy
}

// New builds a Handler forwarding to upstream.
func New(upstream *url.URL, inspector Inspector, recorder Recorder, log *slog.Logger) *Handler {
	h := &Handler{inspector: inspector, recorder: recorder, log: log}
	h.upstream = &httputil.ReverseProxy{
		Rewrite: func(pr *httputil.ProxyRequest) {
			pr.SetURL(upstream)
			pr.SetXForwarded()
			// Keep the client's Host like Caddy and Traefik do, so virtual hosts
			// and absolute URLs generated by the upstream keep working.
			pr.Out.Host = pr.In.Host
		},
		ErrorHandler: h.upstreamError,
		ErrorLog:     slog.NewLogLogger(log.Handler(), slog.LevelError),
	}
	return h
}

func (h *Handler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	verdict, closeTx := h.inspect(r)
	defer closeTx()

	if verdict.Interrupted {
		h.record(r, verdict, verdict.Status)
		http.Error(w, fmt.Sprintf("%s\nrequest id: %s", http.StatusText(verdict.Status), verdict.TxID), verdict.Status)
		return
	}

	sw := &statusWriter{ResponseWriter: w}
	h.upstream.ServeHTTP(sw, r)

	if len(verdict.Matches) > 0 {
		h.record(r, verdict, sw.statusCode())
	}
}

// inspect runs the inspector and fails open: on error or panic the request
// proceeds as if nothing matched.
func (h *Handler) inspect(r *http.Request) (v waf.Verdict, closeTx func()) {
	closeTx = func() {}
	defer func() {
		if p := recover(); p != nil {
			h.log.Error("inspector panic, request passed", "panic", fmt.Sprint(p), "path", redact.String(r.URL.Path))
			v = waf.Verdict{}
		}
	}()

	v, c, err := h.inspector.Inspect(r)
	if c != nil {
		closeTx = safeClose(c, h.log)
	}
	if err != nil {
		h.log.Error("inspector failed, request passed", "err", err, "path", redact.String(r.URL.Path))
		return waf.Verdict{}, closeTx
	}
	return v, closeTx
}

func safeClose(c func(), log *slog.Logger) func() {
	return func() {
		defer func() {
			if p := recover(); p != nil {
				log.Error("inspector close panic", "panic", fmt.Sprint(p))
			}
		}()
		c()
	}
}

func (h *Handler) record(r *http.Request, v waf.Verdict, status int) {
	action := store.ActionDetected
	switch {
	case v.Interrupted:
		action = store.ActionBlocked
	case v.WouldBlock():
		action = store.ActionWouldBlock
	}

	rules := make([]store.Rule, len(v.Matches))
	for i, m := range v.Matches {
		rules[i] = store.Rule{ID: m.RuleID, Message: m.Message, Severity: m.Severity}
	}

	path := r.URL.Path
	if len(path) > maxPathLen {
		path = path[:maxPathLen]
	}

	h.recorder.Record(store.Event{
		Time:      time.Now(),
		RequestID: v.TxID,
		ClientIP:  clientIP(r),
		Method:    r.Method,
		Host:      r.Host,
		Path:      redact.String(path),
		Status:    status,
		Action:    action,
		Rules:     rules,
	})
}

func (h *Handler) upstreamError(w http.ResponseWriter, r *http.Request, err error) {
	h.log.Error("upstream request failed", "err", err, "method", r.Method, "path", redact.String(r.URL.Path))
	w.WriteHeader(http.StatusBadGateway)
}

func clientIP(r *http.Request) string {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		return r.RemoteAddr
	}
	return host
}

// statusWriter captures the response status for the event record.
type statusWriter struct {
	http.ResponseWriter
	status int
}

func (s *statusWriter) WriteHeader(code int) {
	// Informational (1xx) responses precede the final status.
	if s.status == 0 && code >= http.StatusOK {
		s.status = code
	}
	s.ResponseWriter.WriteHeader(code)
}

func (s *statusWriter) Write(b []byte) (int, error) {
	if s.status == 0 {
		s.status = http.StatusOK
	}
	return s.ResponseWriter.Write(b)
}

// Unwrap lets http.ResponseController reach Flush and Hijack on the original writer.
func (s *statusWriter) Unwrap() http.ResponseWriter { return s.ResponseWriter }

func (s *statusWriter) statusCode() int {
	if s.status == 0 {
		return http.StatusOK
	}
	return s.status
}
